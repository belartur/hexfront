//! Build script for the Rust implementation.
//!
//! A browser cannot list a directory, so the web build cannot discover the
//! levels in `maps/` at run time the way the native build does. This script
//! snapshots the sorted file names at compile time into `OUT_DIR`; the wasm
//! branch of `mapfile::list_maps` reads that list and turns every entry into a
//! `maps/<name>.map` URL for `macroquad::file::load_file`.
//!
//! The list is only consumed by the wasm build, but it is generated for every
//! build so a switch of target needs no extra step. `rerun-if-changed` entries
//! make Cargo regenerate it when a map is added, removed or renamed.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let maps_dir = manifest_dir
        .parent()
        .expect("rust/ must have a parent repository root")
        .join("maps");
    println!("cargo:rerun-if-changed={}", maps_dir.display());

    let mut names = Vec::new();
    match fs::read_dir(&maps_dir) {
        Ok(entries) => {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.extension().and_then(|e| e.to_str()) != Some("map") {
                    continue;
                }
                let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
                    continue;
                };
                // A level added later must invalidate this script's output too,
                // not only the directory timestamp.
                println!("cargo:rerun-if-changed={}", path.display());
                names.push(name.to_owned());
            }
        }
        Err(err) => {
            println!("cargo:warning=cannot read {}: {err}", maps_dir.display());
        }
    }
    names.sort();

    let mut out = String::from(
        "// Generated by build.rs: sorted names of the bundled maps/*.map files.\n\
         pub const MAP_FILES: &[&str] = &[\n",
    );
    for name in &names {
        out.push_str(&format!("    {name:?},\n"));
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("maps_bundle.rs"), out).expect("cannot write maps_bundle.rs");
}
